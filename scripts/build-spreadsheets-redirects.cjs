// build-spreadsheets-redirects.cjs — Generate a CloudFront Function from one
// site's redirects.toml.
//
// Usage:
//   node scripts/build-spreadsheets-redirects.cjs [--site <name>]
//
// --site defaults to "spreadsheets"; the only other name is "diya-gl".
//
// Reads:  web/<site dir>/redirects.toml
// Writes: web/<site dir>/redirect-function.js

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

// The one name each site answers to on the command line, mapped to its own
// directory under web/ and to the host this generated function's own
// requests arrive on (used only to tell a ci deployment from a prod one).
const SITES = {
  "spreadsheets": { dir: "spreadsheets.diyaccounting.co.uk" },
  "diya-gl": { dir: "diya-gl.co.uk" },
};

const siteFlagIndex = process.argv.indexOf("--site");
const siteName = siteFlagIndex === -1 ? "spreadsheets" : process.argv[siteFlagIndex + 1];
const site = SITES[siteName];
if (!site) {
  throw new Error(`build-spreadsheets-redirects.cjs: --site must be one of ${Object.keys(SITES).join(", ")}, got "${siteName}"`);
}

const TOML_PATH = path.join(ROOT, "web", site.dir, "redirects.toml");
const OUTPUT_PATH = path.join(ROOT, "web", site.dir, "redirect-function.js");

// Minimal TOML parser (supports our subset: key=value, [[array-of-tables]], [table])
function parseTOML(src) {
  var res = {};
  var currentSection = res;
  var lines = src.split(/\r?\n/);

  for (var i = 0; i < lines.length; i++) {
    var line = lines[i].trim();
    if (!line || line.startsWith("#")) continue;

    // Array of tables: [[name]]
    if (line.startsWith("[[")) {
      var name = line.substring(2, line.lastIndexOf("]]")).trim();
      if (!res[name]) res[name] = [];
      var entry = {};
      res[name].push(entry);
      currentSection = entry;
      continue;
    }

    // Table: [name]
    if (line.startsWith("[")) {
      var tname = line.substring(1, line.lastIndexOf("]")).trim();
      if (!res[tname]) res[tname] = {};
      currentSection = res[tname];
      continue;
    }

    // Key = value
    var eqIdx = line.indexOf("=");
    if (eqIdx === -1) continue;
    var key = line.substring(0, eqIdx).trim();
    var val = line.substring(eqIdx + 1).trim();

    // Parse value
    if (val.startsWith('"') && val.endsWith('"')) {
      val = val.substring(1, val.length - 1);
    } else if (val === "true") {
      val = true;
    } else if (val === "false") {
      val = false;
    } else if (!isNaN(val) && val !== "") {
      val = Number(val);
    }

    currentSection[key] = val;
  }

  return res;
}

// Read and parse config
var tomlSrc = fs.readFileSync(TOML_PATH, "utf8");
var config = parseTOML(tomlSrc);
var redirects = config.redirect || [];
var prefixRedirects = config.redirect_prefix || [];
var hostRedirects = config.redirect_host || [];

// Build the static redirect map as a JS object literal
var staticLines = [];
for (var r of redirects) {
  staticLines.push("    " + JSON.stringify(r.from) + ": { to: " + JSON.stringify(r.to) + ", t: " + JSON.stringify(r.target) + " }");
}
var staticMapStr = "{\n" + staticLines.join(",\n") + "\n  }";

// Build the prefix redirect list as a JS array literal. A whole subtree moved
// to a new path gets one rule here instead of one exact-match entry per file,
// so a file added to the tree later still redirects with no rebuild needed.
var prefixLines = [];
for (var p of prefixRedirects) {
  prefixLines.push("    { from: " + JSON.stringify(p.from) + ", to: " + JSON.stringify(p.to) + ", t: " + JSON.stringify(p.target) + " }");
}
var prefixArrayStr = "[\n" + prefixLines.join(",\n") + "\n  ]";

// Build the host redirect list as a JS array literal: each entry's "from" is
// matched as the whole Host header or a dot-separated suffix of it (so
// "diya-gl.com" also catches "ci.diya-gl.com" and "www.diya-gl.com"), and
// applied in order against the result of every earlier match -- so a host
// two rules both touch (www.diya-gl.com: the .com rule, then the www one)
// resolves in the one redirect rather than a second round trip.
var hostLines = [];
for (var h of hostRedirects) {
  hostLines.push("    { from: " + JSON.stringify(h.from) + ", to: " + JSON.stringify(h.to) + " }");
}
var hostArrayStr = "[\n" + hostLines.join(",\n") + "\n  ]";

// Generate CloudFront Function (JS 2.0 runtime)
var functionCode = `// Auto-generated by scripts/build-spreadsheets-redirects.cjs — do not edit
// SPDX-License-Identifier: LicenseRef-PolyForm-Internal-Use-1.0.0
// Copyright (C) 2006-2026 DIY Accounting Limited
// CloudFront Function for URL redirects
function handler(event) {
  var request = event.request;
  var uri = request.uri;
  var host = (request.headers.host && request.headers.host.value) || '';

  // Detect environment from Host header -- "ci-" for spreadsheets.
  // diyaccounting.co.uk's own convention, "ci." for diya-gl.co.uk's.
  var isCI = host.indexOf('ci-') === 0 || host.indexOf('ci.') === 0;

  // Environment-specific target hosts
  var hosts = {
    spreadsheets: isCI ? 'ci-spreadsheets.diyaccounting.co.uk' : 'spreadsheets.diyaccounting.co.uk',
    submit: isCI ? 'ci.submit.diyaccounting.co.uk' : 'submit.diyaccounting.co.uk',
    'diya-gl': isCI ? 'ci.diya-gl.co.uk' : 'diya-gl.co.uk'
  };

  // Static redirect map (exact path match)
  var redirectMap = ${staticMapStr};

  // Prefix redirects: a whole subtree moved to a new path, checked in order
  // after the exact-match map misses.
  var prefixRedirects = ${prefixArrayStr};

  // Host redirects: this site answering on a domain alias it does not treat
  // as canonical (a .com twin, or "www" beside an apex).
  var hostRedirects = ${hostArrayStr};

  // Helper: return 301 redirect
  function redirect(url) {
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: {
        'location': { value: url },
        'cache-control': { value: 'max-age=86400' }
      }
    };
  }

  // Helper: build target URL
  function targetUrl(target, path) {
    if (target === 'self') return path;
    return 'https://' + hosts[target] + path;
  }

  // Check host redirects first: a request on a non-canonical domain alias
  // is sent to the canonical host before any path rule is even considered.
  // Applied in sequence against the running result, so a host two rules
  // both touch resolves to its final host in the one redirect.
  var newHost = host;
  for (var h = 0; h < hostRedirects.length; h++) {
    var hr = hostRedirects[h];
    if (newHost === hr.from || newHost.slice(-(hr.from.length + 1)) === '.' + hr.from) {
      newHost = newHost.slice(0, newHost.length - hr.from.length) + hr.to;
    }
  }
  if (newHost !== host) {
    return redirect('https://' + newHost + uri);
  }

  // Check static redirect map (exact path match)
  var rule = redirectMap[uri];
  if (rule) {
    // Self-target means rewrite URI (no external redirect)
    if (rule.t === 'self') {
      request.uri = rule.to;
      return request;
    }
    return redirect(targetUrl(rule.t, rule.to));
  }

  // Check prefix redirects (every path under the old subtree, including one
  // added after this function was last built)
  for (var i = 0; i < prefixRedirects.length; i++) {
    var p = prefixRedirects[i];
    if (uri.indexOf(p.from) === 0) {
      var newPath = p.to + uri.slice(p.from.length);
      if (p.t === 'self') {
        request.uri = newPath;
        return request;
      }
      return redirect(targetUrl(p.t, newPath));
    }
  }

  // Pass through to origin
  return request;
}
`;

fs.writeFileSync(OUTPUT_PATH, functionCode, "utf8");
console.log("CloudFront Function written to " + OUTPUT_PATH);
console.log("Site: " + siteName);
console.log(
  "Static redirects: " + redirects.length + ", prefix redirects: " + prefixRedirects.length + ", host redirects: " + hostRedirects.length,
);

// Validate size (CloudFront Functions have 10KB limit)
var sizeKB = Buffer.byteLength(functionCode, "utf8") / 1024;
console.log("Function size: " + sizeKB.toFixed(1) + "KB / 10KB limit");
if (sizeKB > 10) {
  console.error("ERROR: Function exceeds 10KB CloudFront Functions limit!");
  process.exit(1);
}
